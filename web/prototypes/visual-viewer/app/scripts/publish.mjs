// Inline the built JS and CSS into one HTML file and write it to ../index.html (the file the installer copies).
// The view-data.js tag must stay byte-identical: build_view.py --standalone replaces it with the data.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { execSync } from 'node:child_process'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const dist = join(here, '..', 'dist')
const target = join(here, '..', '..', 'index.html')
const DATA_TAG = '<script src="view-data.js" charset="utf-8"></script>'

let html = readFileSync(join(dist, 'index.html'), 'utf8')
const assets = join(dist, 'assets')
const files = readdirSync(assets)
const js = files.filter((f) => f.endsWith('.js'))
const css = files.filter((f) => f.endsWith('.css'))
if (js.length !== 1 || css.length !== 1) throw new Error(`expected one js and one css asset, got ${files.join(', ')}`)

// The report page for "보고서로 보기" (scripts/jinha-report.mjs) is a string with its own <script> and <style> tags.
// Inside the inline script a closing tag would end it early, so it is written as <\/script> (the same string to JS).
const code = readFileSync(join(assets, js[0]), 'utf8').replace(/<\/(script|style)/gi, '<\\/$1')
if (code.includes('<!--')) throw new Error('bundle contains "<!--", which can change how the inline script is parsed')
const style = readFileSync(join(assets, css[0]), 'utf8')
if (/<\/script/i.test(code) || /<\/style/i.test(style)) throw new Error('bundle contains a closing script/style tag')
if (code.includes(DATA_TAG)) throw new Error('bundle must not contain the view-data.js tag')

const scriptTag = new RegExp(`<script type="module" crossorigin src="\./assets/${js[0].replace('.', '\.')}"></script>`)
const linkTag = new RegExp(`<link rel="stylesheet" crossorigin href="\./assets/${css[0].replace('.', '\.')}">`)
if (!scriptTag.test(html) || !linkTag.test(html)) throw new Error('asset tags not found in dist/index.html')
html = html.replace(linkTag, () => `<style>\n${style}\n</style>`)
html = html.replace(scriptTag, () => '')
html = html.replace('</body>', () => `<script type="module">\n${code}\n</script>\n</body>`)
if (html.split(DATA_TAG).length !== 2) throw new Error('view-data.js tag missing or duplicated')

const banner = '<!-- Built from web/prototypes/visual-viewer/app (npm run build). Edit the app sources, not this file. -->\n'
html = html.replace(/\r\n/g, '\n').replace(/^<!doctype html>\n?/i, () => '<!doctype html>\n' + banner)
if (!html.startsWith('<!doctype html>\n<!-- Built')) throw new Error('doctype missing')

// Third-party notices: the licence text of every bundled production package (deduplicated). Kept as an HTML comment at
// the end so copies of index.html carry them.
function notices() {
  const appDir = join(here, '..')
  const paths = execSync('npm ls --omit=dev --all --parseable', { cwd: appDir, encoding: 'utf8' }).split(/\r?\n/).filter(Boolean).slice(1)
  const byText = new Map()
  for (const dir of new Set(paths)) {
    const pkgFile = join(dir, 'package.json')
    if (!existsSync(pkgFile)) continue
    const pkg = JSON.parse(readFileSync(pkgFile, 'utf8'))
    const lic = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
    const text = lic ? readFileSync(join(dir, lic), 'utf8').replace(/\r\n/g, '\n').trim() : `License: ${pkg.license || 'see package'}`
    byText.set(text, [...(byText.get(text) || []), `${pkg.name}@${pkg.version}`])
  }
  const parts = [
    'THIRD-PARTY NOTICES (generated by scripts/publish.mjs)',
    ...[...byText].sort((a, b) => a[1][0].localeCompare(b[1][0])).map(([text, pkgs]) => `${pkgs.sort().join(', ')}\n\n${text}`),
  ]
  return '<!--\n' + parts.join('\n\n----------------------------------------\n\n').replace(/-->/g, '-- >') + '\n-->\n'
}
html = html.replace(/<\/html>\s*$/i, () => '</html>\n' + notices())
if (!html.includes('THIRD-PARTY NOTICES')) throw new Error('notices missing')
writeFileSync(target, html, 'utf8')
console.log(`wrote ${target} (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB)`)
